/** 登録表のカードに、置き場所と名前を足す（data/cards/index.ts が、読み込みの後に1回だけ呼ぶ） */
export function applyMergedPlacement(get: (id: string) => CardDef) {
  for (const [id, p] of Object.entries(MERGED_PLACEMENT)) {
    const c = get(id);
    if (p.name) c.name = p.name;
    if (p.weaponTypes) c.weaponTypes = [...new Set([...(c.weaponTypes ?? []), ...p.weaponTypes])].filter((t) => t !== c.weaponType);
    if (p.lineages) c.lineages = [...new Set([...(c.lineages ?? []), ...p.lineages])].filter((l) => l !== c.lineage);
    if (p.common) c.common = true;
  }
}
